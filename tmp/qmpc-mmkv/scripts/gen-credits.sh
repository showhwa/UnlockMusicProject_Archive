#!/usr/bin/env bash
# Merge license / unlicense files from Meson wrap subprojects into credits.txt.
# Requires wraps to be checked out under subprojects/ (e.g. after `meson setup`).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SUBPROJECTS="${ROOT}/subprojects"
OUT="${1:-${ROOT}/credits.txt}"

# Prefer common SPDX / project names; first match wins per package.
LICENSE_NAMES=(
  LICENSE
  LICENSE.txt
  LICENSE.md
  LICENSE.TXT
  COPYING
  COPYING.txt
  UNLICENSE
  unlicense.txt
  COPYRIGHT
  NOTICE
)

die() {
  printf '%s\n' "$*" >&2
  exit 1
}

wrap_field() {
  # Usage: wrap_field <wrap-file> <key>
  local wrap="$1" key="$2"
  sed -n "s/^[[:space:]]*${key}[[:space:]]*=[[:space:]]*//p" "$wrap" | head -n1
}

find_license() {
  local dir="$1"
  local name path
  for name in "${LICENSE_NAMES[@]}"; do
    path="${dir}/${name}"
    if [[ -f "$path" ]]; then
      printf '%s\n' "$path"
      return 0
    fi
  done
  # Case-insensitive fallback for odd renames.
  path="$(find "$dir" -maxdepth 1 -type f \( \
    -iname 'license' -o -iname 'license.*' -o \
    -iname 'copying' -o -iname 'copying.*' -o \
    -iname 'unlicense' -o -iname 'unlicense.*' -o \
    -iname 'copyright' -o -iname 'notice' \
  \) | sort | head -n1 || true)"
  [[ -n "$path" ]] || return 1
  printf '%s\n' "$path"
}

[[ -d "$SUBPROJECTS" ]] || die "missing ${SUBPROJECTS}"

shopt -s nullglob
wraps=("${SUBPROJECTS}"/*.wrap)
((${#wraps[@]} > 0)) || die "no *.wrap under ${SUBPROJECTS}"

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
  printf '%s\n' \
    'Third-party licenses' \
    '====================' \
    '' \
    'Generated by scripts/gen-credits.sh from Meson wrap subprojects.' \
    "Do not edit by hand; re-run the script after updating wraps." \
    ''
} >"$tmp"

missing=0
for wrap in "${wraps[@]}"; do
  name="$(basename "$wrap" .wrap)"
  directory="$(wrap_field "$wrap" directory)"
  source_url="$(wrap_field "$wrap" source_url)"

  [[ -n "$directory" ]] || die "${wrap}: missing directory="

  pkg_dir="${SUBPROJECTS}/${directory}"
  if [[ ! -d "$pkg_dir" ]]; then
    printf 'warning: %s not checked out (run meson setup)\n' "$directory" >&2
    missing=1
    continue
  fi

  if ! license="$(find_license "$pkg_dir")"; then
    printf 'warning: no license file in %s\n' "$directory" >&2
    missing=1
    continue
  fi

  {
    printf '%s\n' \
      '------------------------------------------------------------------------' \
      "${name}" \
      "  wrap:      $(basename "$wrap")" \
      "  directory: ${directory}" \
      "  license:   $(basename "$license")"
    [[ -n "$source_url" ]] && printf '  source:    %s\n' "$source_url"
    printf '%s\n\n' '------------------------------------------------------------------------'
    # Strip trailing blank lines; keep a single newline before the next section.
    sed -e :a -e '/^\n*$/{$d;N;ba' -e '}' "$license"
    printf '\n\n'
  } >>"$tmp"
done

# Trim trailing blank lines from the whole file.
sed -e :a -e '/^\n*$/{$d;N;ba' -e '}' "$tmp" >"${tmp}.trim"
mv "${tmp}.trim" "$tmp"

mkdir -p "$(dirname "$OUT")"
cp "$tmp" "$OUT"
printf 'wrote %s\n' "$OUT" >&2

((missing == 0)) || exit 1
